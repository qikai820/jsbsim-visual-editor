#!/usr/bin/env python3
"""Extract the CC0 visual hull, unchanged, for the native moving collision mesh."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--runtime-root', type=Path, default=root.parent / 'jsbsim_realtime')
args = parser.parse_args()
source = root / 'client/public/scenery/moving-platform/vessel.glb'
data = source.read_bytes()
length = struct.unpack_from('<I', data, 12)[0]
doc = json.loads(data[20:20 + length])
binary = data[28 + length:]

def accessor(index):
    item = doc['accessors'][index]
    view = doc['bufferViews'][item['bufferView']]
    code = {5123: 'H', 5125: 'I', 5126: 'f'}[item['componentType']]
    width = {'SCALAR': 1, 'VEC3': 3}[item['type']]
    fmt = '<' + code * width
    offset = view.get('byteOffset', 0) + item.get('byteOffset', 0)
    stride = view.get('byteStride', struct.calcsize(fmt))
    return [struct.unpack_from(fmt, binary, offset + i * stride) for i in range(item['count'])]

assert len(doc['nodes']) == 1 and doc['nodes'][0].get('mesh') == 0
assert not any(key in doc['nodes'][0] for key in ['matrix', 'translation', 'rotation', 'scale'])
triangles = []
source_triangles = 0
for primitive in doc['meshes'][0]['primitives']:
    assert primitive.get('mode', 4) == 4
    vertices = accessor(primitive['attributes']['POSITION'])
    indices = [i[0] for i in accessor(primitive['indices'])] if 'indices' in primitive else list(range(len(vertices)))
    source_triangles += len(indices)//3
    for i in range(0,len(indices),3):
        triangle=[vertices[indices[i+j]] for j in range(3)]
        ab=[triangle[1][j]-triangle[0][j] for j in range(3)]
        ac=[triangle[2][j]-triangle[0][j] for j in range(3)]
        cross=[ab[1]*ac[2]-ab[2]*ac[1],ab[2]*ac[0]-ab[0]*ac[2],ab[0]*ac[1]-ab[1]*ac[0]]
        if math.sqrt(sum(v*v for v in cross))>=1e-10:
            triangles.append(triangle)
points = [p for triangle in triangles for p in triangle]
lo = [min(p[i] for p in points) for i in range(3)]
hi = [max(p[i] for p in points) for i in range(3)]
header = '// Generated by scripts/generate-moving-platform-hull.py; do not edit.\n'
header += '// Kenney Watercraft Kit, ship-cargo-c, CC0-1.0: https://kenney.nl/assets/watercraft-kit\n'
header += '// Source GLB SHA-256: ' + hashlib.sha256(data).hexdigest() + '\n#pragma once\n'
header += '#include "input_output/FGSceneMesh.h"\nnamespace JSBSim { namespace MovingShipAsset {\n'
vector = lambda p: '{' + ','.join(format(x, '.17g') for x in p) + '}'
header += 'static const Scene::V minimum=' + vector(lo) + ', maximum=' + vector(hi) + ';\n'
header += 'static const Scene::Triangle triangles[]={\n'
header += ',\n'.join('{' + ','.join(vector(p) for p in triangle) + '}' for triangle in triangles)
header += '\n};\n}}\n'
destination = args.runtime_root / 'src/models/MovingShipAsset.h'
destination.write_text(header)
manifest_path=source.parent/'visual-model.json'
manifest=json.loads(manifest_path.read_text())
manifest['collision']={'sourceSha256':hashlib.sha256(data).hexdigest(),'hullTriangles':len(triangles),
    'deckTriangles':12,'triangles':len(triangles)+12,'removedDegenerateTriangles':source_triangles-len(triangles),
    'runtimeCapability':'moving_platform_mesh=1','generator':'scripts/generate-moving-platform-hull.py'}
manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'file': str(destination), 'triangles': len(triangles), 'sourceSha256': hashlib.sha256(data).hexdigest()}))
