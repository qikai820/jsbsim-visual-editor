import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
const directory = await mkdtemp('/tmp/scene-instruments-');
try {
  await build({ entryPoints: ['client/src/sim/sceneInstruments.ts'], outfile: `${directory}/instruments.cjs`, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
  await build({ entryPoints: ['client/src/sim/flightSceneState.ts'], outfile: `${directory}/state.cjs`, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
  await build({ entryPoints: ['client/src/sim/sceneSignals.ts'], outfile: `${directory}/signals.cjs`, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
  const require = createRequire(import.meta.url);
  const { defaultSceneDisplay, decodeSceneDisplay, resizeSceneValues, newSceneValue, sceneValueReading, sceneCustomPath, sceneValueKeys, compassAttitude } = require(`${directory}/instruments.cjs`);
  const { decodeScenePose, demoPackets } = require(`${directory}/state.cjs`);
  const { sceneMonitorKeys, mergeSceneMonitorKeys, SCENE_POSE_KEYS } = require(`${directory}/signals.cjs`);
  const defaults = defaultSceneDisplay();
  assert.equal(defaults.values.cells.length, 10);
  const shrunk = resizeSceneValues(defaults.values, 1, 3);
  assert.equal(shrunk.cells.length, 3); assert.equal(shrunk.overflow.length, 7);
  const restored = decodeSceneDisplay(JSON.parse(JSON.stringify({ ...defaults, values: shrunk })));
  assert.deepEqual(restored.values, shrunk, 'truncated cells survive persistence in the spare tray');
  const malformed = decodeSceneDisplay({ version: 1, values: { rows: -5, columns: 999, cells: [{ source: 'unknown' }, { source: 'roll', precision: Infinity, label: '<script>', scale: NaN }] } });
  assert.equal(malformed.values.rows, 1); assert.equal(malformed.values.columns, 8);
  assert.equal(malformed.values.cells[0], null); assert.equal(malformed.values.cells[1].precision, 1);
  assert.deepEqual(decodeSceneDisplay(null), defaults);
  assert.equal(sceneCustomPath('/01/jsbsim[0]/fcs/esc-out[0]'), 'fcs/esc-out');
  for (const invalid of ['x; reboot', '../secret', '<script>', 'x\ny', 'a'.repeat(201)]) assert.equal(sceneCustomPath(invalid), '');
  const pose = { ...decodeScenePose(demoPackets(12)[0], 1000), altitude: 110, roll: -12, pitch: 5, yaw: -1, speed: 10, verticalSpeed: -2, groundSampleAt: 1000 };
  let reading = sceneValueReading(newSceneValue('agl'), pose, 100, 1050);
  assert.equal(reading.text, '10.0'); assert.equal(reading.stale, false);
  assert.equal(sceneValueReading(newSceneValue('agl'), pose, null, 1050).text, '—');
  assert.equal(sceneValueReading({ ...newSceneValue('speed'), unit: 'km/h' }, pose, 100, 1050).text, '36.0');
  assert.equal(sceneValueReading({ ...newSceneValue('roll'), unit: 'rad', precision: 3 }, pose, 100, 1050).text, '-0.209');
  assert.equal(sceneValueReading(newSceneValue('heading'), pose, 100, 1050).text, '359.0');
  assert.equal(sceneValueReading(newSceneValue('time'), { ...pose, time: 3661 }, 100, 1050).text, '01:01:01');
  reading = sceneValueReading(newSceneValue('roll'), pose, 100, 3100);
  assert.equal(reading.text, '-12.0'); assert.equal(reading.stale, true);
  const custom = { ...newSceneValue('custom'), path: 'fcs/custom-rad', scale: 2, offset: 1 };
  const sample = { value: 3, seen: 1020, generation: `${pose.model}:${pose.generation}` };
  assert.equal(sceneValueReading(custom, pose, 100, 1050, sample).text, '7.0');
  assert.equal(sceneValueReading(custom, { ...pose, generation: 'another-model-generation' }, 100, 1050, sample).text, '—');
  assert.equal(sceneValueReading(custom, pose, 100, 4000, sample).stale, true);
  assert.deepEqual(sceneValueKeys({ ...defaults.values, cells: [custom, { ...custom }, { ...custom, path: 'bad path' }] }), ['fcs/custom-rad']);
  const keys = mergeSceneMonitorKeys(['user/existing'], sceneMonitorKeys('voliro_t', ['fcs/custom-rad']));
  assert.equal(keys.length, 32); assert.ok(keys.includes('user/existing')); assert.ok(keys.includes('fcs/custom-rad'));
  assert.ok(SCENE_POSE_KEYS.every(key => keys.includes(key)));
  const occupied = Array.from({ length: 32 }, (_, i) => `user/${i}`);
  assert.deepEqual(new Set(mergeSceneMonitorKeys(occupied, sceneMonitorKeys('voliro_t', ['fcs/custom-rad']))), new Set(occupied));
  assert.deepEqual(compassAttitude(370, 45, 10, false), { heading: 10, dial: 0, arrow: 10, rollArc: 30, pitchArc: -10 });
  assert.deepEqual(compassAttitude(-10, -45, -15, true), { heading: 350, dial: -350, arrow: 0, rollArc: -30, pitchArc: 15 });
  console.log('Scene instruments: persistence, spare cells, conversions, freshness, custom generation isolation, monitor capacity and QGC attitude signs passed.');
} finally { await rm(directory, { recursive: true, force: true }); }
