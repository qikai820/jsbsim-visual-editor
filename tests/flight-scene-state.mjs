import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
const directory = await mkdtemp(path.join(tmpdir(), 'flight-scene-state-'));
try {
  const output = path.join(directory, 'scene.cjs');
  await build({ entryPoints: [fileURLToPath(new URL('../client/src/sim/flightSceneState.ts', import.meta.url))], outfile: output, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
  const { FlightSceneFeed, decodeScenePose, sceneProperty, propertyAgeMs, localPosition, sceneAttitude, bodyToSceneBasis, demoPackets, geocentricLatitude } = createRequire(import.meta.url)(output);
  const packet = (t, extra = {}) => ({ ...demoPackets(t)[0], ...extra });
  const pose = decodeScenePose(packet(1), 1000);
  assert.equal(pose.id, '01'); assert.equal(pose.motors.length, 5); assert.ok(pose.tilt > 0);
  for (const bad of [NaN, Infinity, '34']) assert.equal(decodeScenePose(packet(1, { latitude_deg: bad }), 1000), null);
  assert.equal(decodeScenePose(packet(1, { latitude_deg: 91 }), 1000), null);
  assert.equal(decodeScenePose(packet(1, { instance_id: '33' }), 1000), null);
  const staleProps = packet(1); staleProps.scene_property_age_ms = Object.fromEntries(Object.keys(staleProps.properties).map(k => [k, 2100]));
  assert.equal(decodeScenePose(staleProps, 1000).tilt, pose.tilt, 'slow rotating properties retain the last measured value');
  assert.equal(propertyAgeMs(decodeScenePose(staleProps, 1000).tiltSampleAt, 1000), 2100);
  assert.equal(sceneProperty(staleProps, 'fcs/voliro_t/pitch-rad'), undefined, 'stale values remain distinguishable from fresh samples');
  assert.equal(propertyAgeMs(decodeScenePose(packet(1, { age_ms: 3000 }), 1000).tiltSampleAt, 1000), 3000);
  const aliased = packet(1); aliased.properties = { '/01/jsbsim/fcs[0]/esc-out[0]': .45, '/02/jsbsim/fcs[0]/esc-out[1]': .99 };
  aliased.scene_property_age_ms = Object.fromEntries(Object.keys(aliased.properties).map(k => [k, 0]));
  assert.equal(decodeScenePose(aliased, 1000).motors[0], .45);
  assert.equal(decodeScenePose(aliased, 1000).motors[1], null, 'foreign-instance properties cannot animate this aircraft');
  const origin = { latitude: 34, longitude: 109, altitude: 500 };
  assert.ok(localPosition({ latitude: 34, longitude: 109, altitude: 512 }, origin).distanceTo({ x: 0, y: 12, z: 0 }) < 1e-6);
  assert.ok(localPosition({ latitude: 34.001, longitude: 109, altitude: 500 }, origin).z < -110);
  assert.ok(localPosition({ latitude: 34, longitude: 109.001, altitude: 500 }, origin).x > 90);
  // Cardinal headings and positive aerospace roll/pitch in right/up/aft scene axes.
  const vector = localPosition({ latitude: 34, longitude: 109, altitude: 500 }, origin);
  assert.ok(vector.set(1, 0, 0).applyQuaternion(bodyToSceneBasis()).distanceTo({ x: 0, y: 0, z: -1 }) < 1e-9, 'body X axis points forward');
  assert.ok(vector.set(0, 0, -1).applyQuaternion(sceneAttitude({ roll: 0, pitch: 0, yaw: 90 })).distanceTo({ x: 1, y: 0, z: 0 }) < 1e-9);
  assert.ok(vector.set(0, 0, -1).applyQuaternion(sceneAttitude({ roll: 0, pitch: 30, yaw: 0 })).y > .49);
  assert.ok(vector.set(1, 0, 0).applyQuaternion(sceneAttitude({ roll: 30, pitch: 0, yaw: 0 })).y < -.49);
  assert.ok(Math.abs(geocentricLatitude(33.8935374, 583) - 34.07189) < .0001);
  const interleaved = new FlightSceneFeed();
  const detailed = packet(10);
  interleaved.ingest(detailed, 1000);
  const raw = packet(10.04);
  delete raw.properties; delete raw.scene_property_age_ms;
  delete raw.groundspeed_mps; delete raw.vertical_speed_mps;
  interleaved.ingest(raw, 1040, 'fallback');
  assert.equal(interleaved.aircraft.get('01').latest.tilt, decodeScenePose(detailed, 1000).tilt,
    'ordinary telemetry must not blank the inspector between dedicated scene snapshots');
  assert.equal(interleaved.aircraft.get('01').latest.speed, 2.8);
  interleaved.ingest(packet(10.08, { age_ms: 3000 }), 4080);
  interleaved.ingest(packet(10.12), 4090, 'fallback');
  assert.ok(propertyAgeMs(interleaved.aircraft.get('01').latest.tiltSampleAt, 4090) >= 3000, 'fallback cannot revive expired scene properties');
  assert.equal(interleaved.sample('01', 4090).stale, true, 'fallback cannot hide loss of the authoritative stream');
  const fallbackOnly = new FlightSceneFeed();
  fallbackOnly.ingest(raw, 1000, 'fallback');
  assert.equal(fallbackOnly.aircraft.get('01').latest.time, 10.04, 'legacy-only telemetry still supplies poses');
  fallbackOnly.ingest(packet(10.04), 1001);
  assert.notEqual(fallbackOnly.aircraft.get('01').latest.tilt, null, 'same-frame primary snapshot upgrades a fallback pose');
  fallbackOnly.ingest({ ...raw, instance_id: '02' }, 1040, 'fallback');
  assert.equal(fallbackOnly.aircraft.size, 2, 'primary source selection is per aircraft');
  const oldDesktop = new FlightSceneFeed();oldDesktop.ingest(packet(20),2000);
  const capturedAt=oldDesktop.aircraft.get('01').latest.receivedAt;
  const observed={instance_id:'01',model:'voliro_t',tree_generation:'demo',timestamp:20.1,age_ms:5,
    monitor:{version:1,sequence:1,samples:{'fcs/voliro_t/pitch-rad':[.75,20.1,false]}}};
  oldDesktop.ingestMonitor(observed,2100);
  assert.equal(oldDesktop.aircraft.get('01').latest.tilt,.75,'existing desktop monitor queues drive the actual servo too');
  assert.equal(oldDesktop.aircraft.get('01').latest.receivedAt,capturedAt,'monitor samples cannot refresh body pose age');
  oldDesktop.ingest(packet(20.2),2150);
  assert.equal(oldDesktop.aircraft.get('01').latest.tilt,.75,'slow native property snapshots cannot replace fresh monitored servo data');
  assert.equal(oldDesktop.ingestMonitor(observed,2200),false,'replayed monitor frames do not freshen samples');
  assert.equal(oldDesktop.ingestMonitor({...observed,tree_generation:'previous'},2200),false,'monitor data cannot cross model generations');
  // The high-speed path must carry measured pose too, without depending on a
  // native cache update or confusing servo activity with body freshness.
  const poseKeys = ['position/lat-geod-deg','position/long-gc-deg','position/h-sl-meters',
    'attitude/phi-rad','attitude/theta-rad','attitude/psi-rad'];
  const values = [34.072,108.998,610,Math.PI/6,-Math.PI/9,Math.PI/2];
  const monitored = new FlightSceneFeed();monitored.ingest(packet(20),1000);
  const monitorFrame = (sequence,t,keys=poseKeys,age_ms=0,revision=42) => ({instance_id:'01',model:'voliro_t',
    tree_generation:'demo',state:'running',timestamp:t,age_ms,monitor:{version:1,revision,sequence,
      samples:Object.fromEntries(keys.map(key=>[key,[values[poseKeys.indexOf(key)],t,false]]))}});
  monitored.ingestMonitor(monitorFrame(1,21,poseKeys.slice(0,4)),4000);
  assert.equal(monitored.sample('01',4000).stale,true,'four of six measured channels cannot revive stale pose');
  monitored.ingestMonitor(monitorFrame(2,21.02,poseKeys.slice(4)),4020);
  const measuredPose=monitored.aircraft.get('01').latest;
  assert.equal(measuredPose.poseSource,'monitor');
  assert.equal(measuredPose.receivedAt,4000,'pose freshness uses the oldest actual sample');
  assert.equal(measuredPose.latitude,values[0]);assert.equal(measuredPose.altitude,610);
  assert.ok(Math.abs(measuredPose.roll-30)<1e-9);assert.ok(Math.abs(measuredPose.pitch+20)<1e-9);
  assert.equal(monitored.sample('01',4200).stale,false);
  assert.ok(monitored.sample('01',4200).position.distanceTo(localPosition(pose,monitored.origin))>10,'measured position moves the rendered aircraft');
  assert.equal(monitored.ingestMonitor(monitorFrame(2,21.02,poseKeys.slice(4)),4200),false,'replayed batches cannot refresh pose');
  monitored.ingestMonitor(monitorFrame(3,22,poseKeys.slice(0,4)),4300);
  assert.equal(monitored.aircraft.get('01').latest.receivedAt,4000,'every pose channel must advance for the next pose');
  monitored.ingestMonitor(monitorFrame(4,22.5,poseKeys.slice(4)),4800);
  assert.equal(monitored.aircraft.get('01').latest.receivedAt,4000,'widely separated measurements cannot form a coherent pose');
  monitored.ingestMonitor(monitorFrame(5,22.52,poseKeys.slice(0,4)),4820);
  assert.equal(monitored.aircraft.get('01').latest.receivedAt,4800);
  const staleBodyAt=monitored.aircraft.get('01').latest.receivedAt;
  monitored.ingestMonitor({...monitorFrame(6,23),monitor:{version:1,revision:42,sequence:6,
    samples:{'fcs/voliro_t/pitch-rad':[.8,23,false]}}},7000);
  assert.equal(monitored.aircraft.get('01').latest.tilt,.8);
  assert.equal(monitored.aircraft.get('01').latest.receivedAt,staleBodyAt,'servo-only updates still cannot freshen measured body pose');
  assert.equal(monitored.sample('01',7000).stale,true);
  assert.equal(monitored.ingest(packet(21.01),7050),false,'old native snapshots cannot rewind a monitored pose');
  monitored.ingest(packet(24),7100);
  assert.equal(monitored.aircraft.get('01').latest.poseSource,'telemetry','new complete telemetry may resume normally');
  const startup = new FlightSceneFeed();
  startup.ingestMonitor(monitorFrame(1,25,poseKeys.slice(0,4)),1000);
  assert.equal(startup.aircraft.size,0);
  startup.ingestMonitor(monitorFrame(2,25.02,poseKeys.slice(4)),1020);
  assert.equal(startup.aircraft.size,1,'a complete measured monitor cycle can initialize without a native pose');
  assert.ok(startup.origin);assert.equal(startup.aircraft.get('01').latest.yaw,90);
  const invalid = new FlightSceneFeed();
  invalid.ingestMonitor(monitorFrame(1,26,poseKeys.slice(0,4),3000),1000);
  invalid.ingestMonitor(monitorFrame(2,26.02,poseKeys.slice(4),3000),1020);
  assert.equal(invalid.aircraft.size,0,'cached old sample cycles cannot initialize a live aircraft');
  const badLatitude=monitorFrame(3,27);badLatitude.monitor.samples[poseKeys[0]][0]=91;
  invalid.ingestMonitor(badLatitude,2000);assert.equal(invalid.aircraft.size,0,'measured monitor positions still require valid coordinates');
  const missing=monitorFrame(4,28);missing.monitor.samples[poseKeys[0]]=[null,null,false];
  invalid.ingestMonitor(missing,2100);assert.equal(invalid.aircraft.size,0,'an invalid channel cannot reuse an earlier cached value');
  const rebooted = new FlightSceneFeed();
  rebooted.ingest(packet(600,{capture_monotonic_us:1400e6,scene_epoch:0}),1000);
  rebooted.ingestMonitor(monitorFrame(18000,600),1010);
  assert.equal(rebooted.ingestMonitor(monitorFrame(1,.1),4000),false,'same-revision low counters remain untrusted');
  rebooted.ingestMonitor(monitorFrame(2,.2,poseKeys.slice(0,4),0,777),4010);
  assert.equal(rebooted.sample('01',4010).stale,true,'a new subscription still requires all six pose samples');
  rebooted.ingestMonitor(monitorFrame(3,.22,poseKeys.slice(4),0,777),4030);
  assert.equal(rebooted.aircraft.get('01').latest.time,.22,'acknowledged new subscription recovers the reused generation after reboot');
  assert.equal(rebooted.aircraft.get('01').history.length,1,'the new run has a separate trajectory');
  assert.equal(rebooted.sample('01',4030).stale,false);
  assert.equal(rebooted.ingest(packet(600,{capture_monotonic_us:1400e6,scene_epoch:0,age_ms:3100}),4100),false,'old native caches cannot replace fresh post-reboot sampling');
  assert.equal(rebooted.aircraft.get('01').latest.time,.22);
  const nativeReboot = new FlightSceneFeed();
  nativeReboot.ingest(packet(600,{capture_monotonic_us:1400e6,scene_epoch:0}),1000);
  assert.equal(nativeReboot.ingest(packet(.1,{capture_monotonic_us:500e6,scene_epoch:1}),4000),true,'a confirmed native epoch permits both clocks to start over');
  assert.equal(nativeReboot.aircraft.get('01').history.length,1);
  assert.equal(nativeReboot.ingest(packet(601,{capture_monotonic_us:1401e6,scene_epoch:0}),4100),false,'retired native epochs cannot return');
  const feed = new FlightSceneFeed();
  feed.ingest(packet(1), 1000); feed.ingest(packet(1.04, { yaw_deg: 359 }), 1040); feed.ingest(packet(1.08, { yaw_deg: 1 }), 1080);
  const crossing = feed.sample('01', 1140);
  assert.ok(Math.abs(vector.set(0, 0, -1).applyQuaternion(crossing.quaternion).x) < .02, 'interpolate across north using shortest quaternion arc');
  assert.equal(feed.ingest(packet(1.04, { capture_monotonic_us: 1.04e6 }), 1100), false, 'old packets cannot rewind');
  feed.ingest(packet(1.08, { age_ms: 3000, yaw_deg: 1 }), 4080);
  assert.equal(feed.sample('01', 4080).stale, true, 'cached snapshots cannot refresh freshness');
  feed.ingest(packet(0, { tree_generation: 'next' }), 5000);
  assert.equal(feed.aircraft.get('01').history.length, 1, 'new generation resets trajectory and trend');
  assert.equal(feed.ingest(packet(2), 5010), false, 'retired generations cannot reappear');
  feed.ingest(packet(1, { instance_id: '02', tree_generation: 'next' }), 5100);
  assert.equal(feed.aircraft.size, 2, 'aircraft buffers are independent');
  for (let i = 1; i < 1500; i++) feed.ingest(packet(i * .2, { tree_generation: 'next', longitude_deg: 109 + i * .000001 }), 5000 + i * 200);
  assert.ok(feed.aircraft.get('01').history.length <= 300); assert.ok(feed.aircraft.get('01').trail.length <= 600);
  feed.clearTrails(); assert.equal(feed.aircraft.get('01').trail.length, 0);
  console.log('Flight scene state: coordinate/attitude conventions, interpolation, property age, packet order, generations, freshness and bounds passed.');
} finally { await rm(directory, { recursive: true, force: true }); }
