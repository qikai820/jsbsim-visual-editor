import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
const work = await mkdtemp(`${tmpdir()}/wind-profile-`);
try {
  const output = `${work}/wind.cjs`;
  await build({ stdin: { contents: `export * from './client/src/sim/windProfile';export * from './client/src/sim/runtimeParameters';`, resolveDir: process.cwd() }, outfile: output, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
  const w = createRequire(import.meta.url)(output);
  const p = { ...w.profileFromEnvironment({ windEastFps: -5/.3048 }), active: 1, speedWave: 1, speedAmplitudeMps: 2, speedPeriodSec: 4, directionWave: 2, directionAmplitudeDeg: 30, directionPeriodSec: 8 };
  const near = (a,b) => assert.ok(Math.abs(a-b)<1e-8, `${a} != ${b}`);
  near(p.directionMeanDeg,90);near(p.speedMeanMps,5);
  near(w.windSample(p,1).speed,7);near(w.windSample(p,3).speed,3);
  near(w.windSample(p,2).direction,120);
  near(w.windSample({...p,directionMeanDeg:350},2).direction,20);
  near(w.windSample({...p,speedWave:2},.5).speed,6);
  near(w.windSample({...p,speedWave:3,speedDutyPct:25},1).speed,3);
  near(w.windSample({...p,speedWave:3,speedDutyPct:25},.999).speed,7);
  assert.ok(w.windProfileError({...p,speedAmplitudeMps:6}));
  assert.ok(w.windProfileError({...p,speedPeriodSec:0}));
  assert.ok(w.windProfileError({...p,directionWave:4}));
  assert.ok(w.windProfileError({...p,downMps:NaN}));
  assert.equal(w.windProfileEdits(p).length,14);
  const make = profile => ({ nodes: [{ id:'env', data:{ componentType:'environment', params:{ wind_north_fps:0,wind_east_fps:-5/.3048,wind_down_fps:0, ...(profile ? {wind_profile:profile}: {}) } } }] });
  const old=make(),next=make(p),changed=make({...p,speedAmplitudeMps:3});
  assert.equal(w.projectParameterChanges(old,next).length,14,'first enable sends the whole profile');
  assert.equal(w.projectParameterChanges(next,changed).length,14,'one parameter change remains atomic');
  assert.equal(w.projectParameterChanges(next,make({...p,speedAmplitudeMps:6})).length,0,'invalid draft never generates a command');
  const saved=w.environmentFromProject(changed);
  assert.deepEqual(saved.windProfile,changed.nodes[0].data.params.wind_profile);
  assert.equal(w.environmentEdits(saved).length,0,'fixed NED values cannot overwrite an active profile');
  const legacy=make({...p,active:0});
  assert.equal(w.projectParameterChanges(changed,legacy).length,17,'leaving polar mode disables it before restoring all three fixed components');
  const edited=structuredClone(legacy);edited.nodes[0].data.params.wind_east_fps=12;
  assert.equal(w.projectParameterChanges(legacy,edited).length,17,'fixed edits also disable an unapplied live profile');
  assert.deepEqual(w.projectParameterChanges(changed,structuredClone(changed)),[],'layout and reopen never restart the wind');
  console.log('PASS: wind wave parity, direction wrapping, validation, atomic edits and persistence');
} finally { await rm(work,{recursive:true,force:true}); }
