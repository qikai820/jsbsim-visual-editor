export function getComponentDef(type: string): ComponentDef | undefined {
  return componentDefs.find(d => d.type === type);
}

export function getCategories(): { name: string; defs: ComponentDef[] }[] {
  const cats = new Map<string, ComponentDef[]>();
  for (const def of componentDefs) {
    if (!cats.has(def.category)) cats.set(def.category, []);
    cats.get(def.category)!.push(def);
  }
  return Array.from(cats.entries()).map(([name, defs]) => ({ name, defs }));
}
